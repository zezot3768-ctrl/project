st.title("About this project")
st.markdown("""
**MarketLens** is a first-year Computer Science project that shows how programming can be used to study stock markets:
it retrieves market data from a financial API, cleans and analyzes it, draws charts, and lets you practise
trading with **virtual money**.
""")

st.subheader("Technologies and what each one does")
st.markdown("""
| Technology | Role in this project |
|---|---|
| **Python** | The main language. Every file in this project is Python. |
| **Financial API** (Yahoo Finance by default) | Supplies prices, volume and company figures. The provider can be switched in the configuration. |
| **Pandas** | Stores prices in tables (DataFrames), fills missing values, removes duplicates, and turns daily data into weekly/monthly/yearly data. |
| **NumPy** | Fast maths: square roots for volatility, random numbers for the hypothetical simulation. |
| **Matplotlib** | Static charts such as the histogram of daily returns and the volume bar chart. |
| **Plotly** | Interactive charts (candlesticks, replay, simulations). |
| **Streamlit** | Turns Python scripts into this web application. |
| **SQLite** | Saves your virtual portfolio, transactions and watchlist between sessions. |
| **Jupyter Notebook** | `notebooks/stock_analysis.ipynb` walks through the same analysis step by step. |
""")

st.subheader("How the pieces work")
st.markdown("""
1. **Retrieving data.** `data_fetcher.py` asks the provider for prices. Results are cached for a short time, requests are rate-limited,
   and if a request fails the app shows the last saved data marked **STALE** or a clear error. It never invents prices.
2. **Processing with Pandas.** `data_processor.py` validates the table, fixes missing values and computes daily returns
   (today's close ÷ yesterday's close − 1) and statistics.
3. **Calculating with NumPy.** Volatility is the standard deviation of daily returns multiplied by √252.
4. **Visualizing.** `visualization.py` draws the charts. Green means up, red means down.
5. **Virtual trading.** Trades are stored in SQLite. Holdings are rebuilt from the transaction list using the average-cost method.
   You cannot spend more cash than you have or sell shares you do not own.
6. **Market replay.** Real historical closing prices are revealed one day at a time. Your portfolio is compared with a buy-and-hold benchmark.
7. **Hypothetical market.** Prices are generated by a random model (geometric Brownian motion) from the return and volatility you choose.
""")

st.subheader("The four kinds of data")
st.markdown(f"""
{ui.badge(ui.DataCategory.REAL_TIME)} supplied live by the provider (only if the provider offers real-time data) &nbsp;
{ui.badge(ui.DataCategory.DELAYED)} market is open but the price is delayed &nbsp;
{ui.badge(ui.DataCategory.HISTORICAL)} past prices, including the latest close when the market is closed &nbsp;
{ui.badge(ui.DataCategory.HYPOTHETICAL)} generated by assumptions, not real
""", unsafe_allow_html=True)
st.caption(f"Current provider: {service.provider.label}. {service.provider.delay_note}")

st.subheader("Limitations")
st.markdown("""
- Free data can be delayed, incomplete or briefly unavailable. Rate limits may apply.
- Simulated trades ignore fees, taxes, spreads and the fact that real orders may not fill at the displayed price.
- Indicators describe the past. They do not predict the future, and nothing here is investment advice.
- There are no passwords: the profile name only separates saved portfolios on one computer.
- Market holidays are detected from the data (a weekday with no new price bar), not from an official holiday calendar.
""")

